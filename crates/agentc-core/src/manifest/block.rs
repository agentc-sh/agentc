use sanitizer::prelude::*;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};
use validator::Validate;

use agentc_blocks::context::{
    ResolvedContextBlockContribution, ResolvedContextBlockDependency, ResolvedContextBlockTemplate,
};
use agentc_compiler::generator::loader::ResourceLoader;

use crate::manifest::errors::ManifestError;

#[derive(Debug, Clone, Serialize, Deserialize, Validate, Sanitizer)]
pub struct ManifestBlock {
    /// Optional description of the block.
    #[serde(default)]
    #[validate(length(min = 1))]
    #[sanitizer(trim)]
    pub description: Option<String>,
    /// Files to be generated by this block, keyed by output path.
    #[serde(default)]
    pub generates: BTreeMap<String, ManifestBlockTemplate>,
    /// Extension point contributions, keyed by extension point name.
    #[serde(default)]
    pub contributes: BTreeMap<String, ManifestBlockContribution>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(transparent)]
pub struct ManifestBlockTemplate {
    pub path: String,
}

impl ManifestBlockTemplate {
    pub async fn resolve(
        &self,
        loader: &dyn ResourceLoader,
    ) -> Result<ResolvedContextBlockTemplate, ManifestError> {
        Ok(ResolvedContextBlockTemplate {
            path: self.path.clone(),
            content: loader.load(&self.path).await?,
        })
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum ManifestBlockContribution {
    Text {
        template: ManifestBlockTemplate,
    },
    Tokens {
        template: ManifestBlockTemplate,
    },
    CargoDependencies {
        crates: BTreeMap<String, ManifestBlockDependency>,
    },
}

impl ManifestBlockContribution {
    pub async fn resolve(
        &self,
        loader: &dyn ResourceLoader,
    ) -> Result<ResolvedContextBlockContribution, ManifestError> {
        Ok(match self {
            Self::Text { template } => {
                ResolvedContextBlockContribution::Text(template.resolve(loader).await?)
            }
            Self::Tokens { template } => {
                ResolvedContextBlockContribution::Tokens(template.resolve(loader).await?)
            }
            Self::CargoDependencies { crates } => {
                ResolvedContextBlockContribution::CargoDependencies(
                    crates
                        .iter()
                        .map(|(name, dependency)| dependency.resolve(name))
                        .collect(),
                )
            }
        })
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ManifestBlockDependency {
    #[serde(default)]
    pub version: Option<String>,
    #[serde(default)]
    pub git: Option<String>,
    #[serde(default)]
    pub branch: Option<String>,
    #[serde(default)]
    pub tag: Option<String>,
    #[serde(default)]
    pub rev: Option<String>,
    #[serde(default)]
    pub path: Option<String>,
    #[serde(default)]
    pub default_features: Option<bool>,
    #[serde(default)]
    pub features: BTreeSet<String>,
}

impl ManifestBlockDependency {
    pub fn resolve(&self, name: &str) -> ResolvedContextBlockDependency {
        ResolvedContextBlockDependency {
            name: name.to_string(),
            version: self.version.clone(),
            git: self.git.clone(),
            branch: self.branch.clone(),
            tag: self.tag.clone(),
            rev: self.rev.clone(),
            path: self.path.clone(),
            default_features: self.default_features,
            features: self.features.clone(),
        }
    }
}
